UPDATE outbox_event
SET topic = CASE
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'dispatch:%'
         AND payload_json LIKE '%"outcome":"NO_CANDIDATE"%'
        THEN 'dispatch.no_candidate'
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'dispatch:%'
        THEN 'order.dispatch_requested'
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'offer:%:created'
        THEN 'offer.created'
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'offer:%:ACCEPTED'
        THEN 'offer.accepted'
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'offer:%:REJECTED'
        THEN 'offer.rejected'
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'offer:%:EXPIRED'
        THEN 'offer.expired'
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'offer:%:SUPERSEDED'
        THEN 'offer.superseded'
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'order:%:created:v%'
        THEN 'order.created'
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'order:%:prep:v%'
        THEN 'merchant.prep_updated'
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'order:%:PICKED_UP:%'
        THEN 'order.picked_up'
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'order:%:DELIVERED:%'
        THEN 'order.delivered'
    WHEN topic = 'peakdispatch.order' AND dedupe_key LIKE 'order:%:status:v%'
        THEN 'order.status_changed'
    WHEN topic = 'peakdispatch.courier' AND dedupe_key LIKE 'capacity:%'
        THEN 'courier.capacity_changed'
    WHEN topic = 'peakdispatch.courier'
        THEN 'courier.presence_changed'
    ELSE topic
END
WHERE topic IN ('peakdispatch.order', 'peakdispatch.courier');
